"""Dataset statistics from the prepared cache -> reports/data_stats.json + reports/01_data.md."""

import argparse
import json
from pathlib import Path

import numpy as np

from ..config import PROJECT_ROOT
from .run import load_prepared


def _win_counts(ws, vids=None):
    idx = np.arange(len(ws.y)) if vids is None else ws.select(vids, labeled_only=False)
    y = ws.y[idx]
    pos, neg, ign = int((y == 1).sum()), int((y == 0).sum()), int((y == -1).sum())
    return {"pos": pos, "neg": neg, "ignored": ign, "neg_per_pos": neg / pos if pos else None}


def compute(prep) -> dict:
    meta = prep.meta
    falls = [m for m in meta.values() if m["label"] == 1]
    adls = [m for m in meta.values() if m["label"] == 0]
    fps = float(np.median([m["fps"] for m in meta.values()]))
    fall_len = [m["fall_span"][1] - m["fall_span"][0] for m in falls if m["fall_span"]]
    fixed = prep.splits["fixed"][0]
    return {
        "dataset": prep.protocol.get("dataset", "urfall-cam0"),
        "videos": len(meta), "fall_videos": len(falls), "adl_videos": len(adls),
        "groups": len({m["group"] for m in meta.values()}),
        "subjects": "not published per sequence by the dataset authors (subject-level split impossible)",
        "fps": fps,
        "frames_total": int(sum(m["frames"] for m in meta.values())),
        "frames_fall_videos": int(sum(m["frames"] for m in falls)),
        "frames_adl_videos": int(sum(m["frames"] for m in adls)),
        "duration_min_total": sum(m["frames"] for m in meta.values()) / fps / 60,
        "frames_per_video": {"min": int(min(m["frames"] for m in meta.values())),
                             "median": float(np.median([m["frames"] for m in meta.values()])),
                             "max": int(max(m["frames"] for m in meta.values()))},
        "no_person_detected_frame_rate": float(np.average([m["missing_rate"] for m in meta.values()],
                                                          weights=[m["frames"] for m in meta.values()])),
        "fall_interval_frames": {"min": int(min(fall_len)), "median": float(np.median(fall_len)),
                                 "max": int(max(fall_len))} if fall_len else None,
        "fall_videos_without_fall_annotation": int(sum(1 for m in falls if not m["fall_span"])),
        "frames_without_official_label": int(sum(m["n_unknown_frames"] for m in meta.values())),
        "window_length": prep.train_ws.length,
        "windows_train_stride": {"stride": prep.train_ws.stride, **_win_counts(prep.train_ws)},
        "windows_eval_stride": {"stride": prep.eval_ws.stride, **_win_counts(prep.eval_ws)},
        "fixed_split": {k: {"videos": len(v), "fall_videos": sum(meta[x]["label"] for x in v),
                            "windows": _win_counts(prep.train_ws if k == "train" else prep.eval_ws, v)}
                        for k, v in fixed.items()},
        "augmentation": "horizontal mirror (x -> -x on mid-hip-centred coords + left/right joint swap), "
                        "training partition only, one mirrored copy per training window (x2)"
                        if prep.protocol["mirror_train"] else "none",
    }


def to_markdown(s: dict) -> str:
    w_tr, w_ev = s["windows_train_stride"], s["windows_eval_stride"]
    fs = s["fixed_split"]
    fi = s["fall_interval_frames"] or {}
    lines = [
        "# 01 — Data", "",
        "Generated by `make data` (`python -m pose_estimation.experiments.data_stats`) from the prepared cache.", "",
        f"* Dataset: **{s['dataset']}** (UR Fall Detection, University of Rzeszów, official cam0 RGB frames + official per-frame labels).",
        f"* Videos: **{s['videos']}** = {s['fall_videos']} fall + {s['adl_videos']} ADL; independent groups: {s['groups']}.",
        f"* Subjects: {s['subjects']}.",
        f"* Frames: {s['frames_total']} ({s['frames_fall_videos']} in fall videos, {s['frames_adl_videos']} in ADL videos), "
        f"{s['fps']:.0f} fps, {s['duration_min_total']:.1f} min total; frames/video min/median/max = "
        f"{s['frames_per_video']['min']}/{s['frames_per_video']['median']:.0f}/{s['frames_per_video']['max']}.",
        f"* Frames where YOLOv8n-pose found no person (interpolated): {100 * s['no_person_detected_frame_rate']:.2f}%.",
        f"* Annotated falling interval (label 0) length, frames: min/median/max = {fi.get('min')}/{fi.get('median')}/{fi.get('max')}; "
        f"fall videos without a usable annotation: {s['fall_videos_without_fall_annotation']}; frames absent from the label CSVs: {s['frames_without_official_label']}.",
        "", "## Windows", "",
        f"Window length {s['window_length']} frames. Positive = contains >= min(8, |fall interval|) annotated falling frames; "
        "negative = ADL window, or fall-video window with no falling/lying frame; ignored = partial overlap or post-fall lying only.", "",
        "| stride | positive | negative | ignored | negative : positive |", "|---|---|---|---|---|",
        f"| {w_tr['stride']} (training) | {w_tr['pos']} | {w_tr['neg']} | {w_tr['ignored']} | {w_tr['neg_per_pos']:.1f} : 1 |",
        f"| {w_ev['stride']} (validation/test) | {w_ev['pos']} | {w_ev['neg']} | {w_ev['ignored']} | {w_ev['neg_per_pos']:.1f} : 1 |",
        "", "## Fixed split (video level, stratified, split_seed 0)", "",
        "| partition | videos | fall videos | positive windows | negative windows |", "|---|---|---|---|---|",
    ]
    for k in ("train", "val", "test"):
        lines.append(f"| {k} | {fs[k]['videos']} | {fs[k]['fall_videos']} | {fs[k]['windows']['pos']} | {fs[k]['windows']['neg']} |")
    lines += ["", f"Augmentation: {s['augmentation']}.", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", type=Path, default=PROJECT_ROOT / "dataset/urfall/cache/prepared.pkl")
    ap.add_argument("--out-dir", type=Path, default=PROJECT_ROOT / "reports")
    a = ap.parse_args()
    stats = compute(load_prepared(a.cache))
    a.out_dir.mkdir(parents=True, exist_ok=True)
    (a.out_dir / "data_stats.json").write_text(json.dumps(stats, indent=2))
    (a.out_dir / "01_data.md").write_text(to_markdown(stats))
    print(to_markdown(stats))


if __name__ == "__main__":
    main()
